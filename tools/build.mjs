import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
export const root=fileURLToPath(new URL('../',import.meta.url));
const shell=readFileSync(root+'Shell.html','utf8');
const html=shell.replace(/<\?!= include_\('([A-Za-z]+)'\); \?>/g,(_,name)=>readFileSync(root+name+'.html','utf8'));
if(html.includes('<?'))throw new Error('Unresolved Apps Script template');
writeFileSync(root+'index.html','<!-- Generated by npm run build. Edit Shell.html and its partials. -->\n'+html);
console.log('Built index.html from Apps Script partials.');
